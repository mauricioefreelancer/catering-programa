BEGIN;

ALTER TABLE "MAQUINAS_Y_TIENDAS"
  ADD COLUMN "Tipo_Negociacion" VARCHAR(20) NOT NULL DEFAULT 'NORMAL'
    CHECK ("Tipo_Negociacion" IN ('NORMAL', 'ESPECIAL')),
  ADD COLUMN "Lectura_NRQ_Espiral" VARCHAR(20) NOT NULL DEFAULT 'CORTE_MES'
    CHECK ("Lectura_NRQ_Espiral" IN ('CORTE_MES', 'CADA_VISITA'));
ALTER TABLE "MAPA_MATERIA_PRIMA"
  ADD COLUMN "Porcentaje_Cliente" DECIMAL(5,2) NOT NULL DEFAULT 0
    CHECK ("Porcentaje_Cliente" BETWEEN 0 AND 100);
ALTER TABLE "MAPA_CAFE_NRQ"
  ADD COLUMN "Porcentaje_Cliente" DECIMAL(5,2) NOT NULL DEFAULT 0
    CHECK ("Porcentaje_Cliente" BETWEEN 0 AND 100);
ALTER TABLE "LECTURAS_NRQ"
  ADD COLUMN "Porcentaje_Cliente" DECIMAL(5,2)
    CHECK ("Porcentaje_Cliente" BETWEEN 0 AND 100);

UPDATE "MAPA_MATERIA_PRIMA" SET "Porcentaje_Cliente" = 100 WHERE "Precio_Cero";
UPDATE "MAQUINAS_Y_TIENDAS" m SET "Tipo_Negociacion" = 'ESPECIAL'
WHERE EXISTS (SELECT 1 FROM "MAPA_MATERIA_PRIMA" e WHERE e."ID_Maquina" = m."ID_Maquina" AND e."Porcentaje_Cliente" = 100);

COMMIT;
